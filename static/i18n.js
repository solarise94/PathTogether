  var STORAGE_KEY = "hp_lang";

  // 当前登录角色（app.js initAuth 注入；docs §8.3：AI 配置标题按 owner/user 区分）
  var _role = null;

  function setRole(role) {
    _role = role || null;
    applyLang(currentLang);
    // 通知动态内容（如 AI 配置面板）按新角色重渲染
    document.dispatchEvent(new CustomEvent("hp-lang-change", { detail: { lang: currentLang } }));
  }

  // 角色相关键：按当前角色重定向到具体键
  var ROLE_KEYS = {
    "ai.config.title": { user: "ai.config.title.user", owner: "ai.config.title.owner" },
  };

  function resolveKey(key) {
    var m = ROLE_KEYS[key];
    if (!m) return key;
    return _role === "user" ? m.user : m.owner;
  }

  function detectLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "zh" || saved === "en") return saved;
    } catch (e) {}
    var nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    return nav.indexOf("zh") === 0 ? "zh" : "en";
  }

  var currentLang = detectLang();

  // 形参替换：t("key", {n:3}) → 模板里的 {n} 替成 3
  function fmt(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, function (_, k) {
      return Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : ("{" + k + "}");
    });
  }

  function t(key, vars) {
    var table = DICT[currentLang] || DICT.zh;
    var s = table[key];
    if (s == null) {
      // 回退到另一种语言，再不行就返回 key 本身（开发期便于发现遗漏）
      s = (DICT.zh[key] != null ? DICT.zh[key] : (DICT.en[key] != null ? DICT.en[key] : key));
    }
    return fmt(s, vars);
  }

  function tResolved(key, vars) {
    // 先做角色重定向（ai.config.title → owner/user 变体），再查表
    return t(resolveKey(key), vars);
  }

  // 表查找（含角色键重定向；重定向键缺失时回退原键）
  function lookup(table, key) {
    var rk = resolveKey(key);
    if (rk !== key && table[rk] != null) return table[rk];
    return table[key];
  }

  function applyLang(lang) {
    var table = DICT[lang] || DICT[currentLang];
    // textContent
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      var s = lookup(table, key);
      if (key && s != null) el.textContent = fmt(s, collectVars(el));
    });
    // placeholder
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-ph");
      var s = lookup(table, key);
      if (key && s != null) el.setAttribute("placeholder", fmt(s, collectVars(el)));
    });
    // title
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-title");
      var s = lookup(table, key);
      if (key && s != null) el.setAttribute("title", fmt(s, collectVars(el)));
    });
    // aria-label
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      var s = lookup(table, key);
      if (key && s != null) el.setAttribute("aria-label", fmt(s, collectVars(el)));
    });
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    // 更新切换按钮文本（所有页面的 .lang-toggle）
    document.querySelectorAll(".lang-toggle").forEach(function (btn) {
      btn.textContent = table["lang.toggle"] || (lang === "zh" ? "EN" : "中");
    });
    // 介绍页 document.title（无 inline script，配合 CSP script-src 'self'）
    if (document.documentElement.getAttribute("data-page") === "entry") {
      var entryTitle = table["app.doc.title.entry"];
      if (entryTitle) document.title = entryTitle;
    }
  }

  // 从元素 data-i18n-vars="n:3;m:2" 解析形参（可选，用于静态节点的 {n}）
  function collectVars(el) {
    var raw = el.getAttribute("data-i18n-vars");
    if (!raw) return null;
    var out = {};
    raw.split(";").forEach(function (pair) {
      var idx = pair.indexOf(":");
      if (idx > 0) out[pair.slice(0, idx).trim()] = pair.slice(idx + 1);
    });
    return out;
  }

  function getLang() { return currentLang; }

  function setLang(lang) {
    if (lang !== "zh" && lang !== "en") lang = "zh";
    currentLang = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    applyLang(lang);
    // 通知动态内容（app.js / share.js）按新语言重渲染
    document.dispatchEvent(new CustomEvent("hp-lang-change", { detail: { lang: lang } }));
  }

  // 页面加载时：先按当前语言铺一遍静态文本（无需等 DOMContentLoaded，本脚本在 body 末尾）
  function autoInit() {
    applyLang(currentLang);
    // 绑定所有切换按钮
    document.querySelectorAll(".lang-toggle").forEach(function (btn) {
      if (btn.dataset.hpBound === "1") return;
      btn.dataset.hpBound = "1";
      btn.addEventListener("click", function () {
        setLang(currentLang === "zh" ? "en" : "zh");
      });
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", autoInit);
  } else {
    autoInit();
  }

  // 对外暴露（app.js / share.js 用 window.HP_I18N.t）
  window.HP_I18N = {
    t: tResolved,
    getLang: getLang,
    setLang: setLang,
    setRole: setRole,
    applyLang: applyLang,
  };
